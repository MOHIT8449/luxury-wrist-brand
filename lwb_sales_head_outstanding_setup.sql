-- LUXURY WRIST BRAND ERP — SALES HEAD: OUTSTANDING + PAYMENT STATUS ON THE PO LIST
--
-- Runs by itself when merged to main. Safe to run again. Nothing is dropped or deleted.
--
-- Mohit asked (20 Nov 2026): the Sales Head sees every bill whose payment has not fully come: total billed,
-- received, outstanding, the list of unpaid / part-paid bills, party-wise totals and the party ledger.
-- On PO / Sales the last column shows the payment of each PO: paid / part / pending, and how it came
-- (cash, GPay / UPI, bank, cheque). From both places the Sales Head can tell Accounts / Cashier.
--
--   * lwb_outstanding_viewer()        Admin, Accounts, Sales Head (manager); active login.
--   * lwb_sales_outstanding(p_days)   read only, same rows and formula as Billing & Outstanding
--                                     (lwb_party_billing): bills with due, advance, opening, party groups,
--                                     returns without a bill; plus the salesman of each PO. No receipts.
--   * lwb_order_payments(order ids)   every payment on a PO: driver cash / online, office payment, party
--                                     payment split to it; mode, date, who, cheque status. Max 1000 ids.
--   * lwb_payment_followup(order, party, note)  Sales Head / Admin tell Accounts, Cashier and Admin
--                                     (notification); same PO / party again only after 30 minutes.
-- Payments are still entered only by Accounts / Cashier.

BEGIN;

CREATE OR REPLACE FUNCTION public.lwb_outstanding_viewer()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $fn$
  SELECT EXISTS (SELECT 1 FROM public.user_profiles p WHERE p.id = auth.uid() AND p.active = true
                 AND lower(btrim(p.role)) IN ('admin','accounts','manager'));
$fn$;
REVOKE ALL ON FUNCTION public.lwb_outstanding_viewer() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_outstanding_viewer() TO authenticated;

-- ---------------------------------------------------------------------------
-- 1. Follow-up log (who told Accounts about which PO / party)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.lwb_payment_followups (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   uuid REFERENCES public.orders(id) ON DELETE CASCADE,
  party      text NOT NULL CHECK (length(party) <= 200),
  note       text CHECK (note IS NULL OR length(note) <= 300),
  due        numeric(14,2),
  sent_to    integer NOT NULL DEFAULT 0,
  created_by uuid NOT NULL,
  created_by_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lwb_payment_followups_order_idx ON public.lwb_payment_followups(order_id, created_at DESC);
CREATE INDEX IF NOT EXISTS lwb_payment_followups_party_idx ON public.lwb_payment_followups(party, created_at DESC);
ALTER TABLE public.lwb_payment_followups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.lwb_payment_followups FROM PUBLIC, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 2. Outstanding data (same shape as lwb_party_billing so the page can use LWBPartyPay.load)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.lwb_sales_outstanding(p_days integer DEFAULT 400)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_days int := least(greatest(coalesce(p_days,400),30),400);
  v_rows jsonb;
BEGIN
  IF NOT public.lwb_outstanding_viewer() THEN
    RAISE EXCEPTION 'Admin / Accounts / Sales Head only.';
  END IF;

  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'order_id', r.order_id, 'order_no', r.order_no, 'party', r.party,
           'parent', public.lwb_party_parent(r.party), 'status', r.status,
           'company_id', public.lwb_order_company(r.order_id),
           'sales_person', nullif(btrim(o.sales_person::text),''),
           'order_date', r.order_date, 'dispatch_date', r.dispatch_date,
           'invoice_no', r.invoice_no, 'invoice_date', r.invoice_date,
           'bill_amount', r.bill_amount, 'erp_amount', r.erp_amount,
           'approved_return', r.approved_return, 'pending_return', r.pending_return,
           'credit_notes', r.credit_notes, 'debit_notes', r.debit_notes,
           'driver', r.collected - public.lwb_order_office_paid(r.order_id),
           'office', public.lwb_order_office_paid(r.order_id),
           'due', r.due, 'credit_pending', r.credit_pending, 'delivery', r.delivery,
           'bills', coalesce(t.bills, '[]'::jsonb), 'entered_at', t.entered_at,
           'told', (SELECT jsonb_build_object('at', f.created_at, 'by', f.created_by_name)
                    FROM public.lwb_payment_followups f WHERE f.order_id = r.order_id
                    ORDER BY f.created_at DESC LIMIT 1))
         ORDER BY r.dispatch_date, r.order_no), '[]'::jsonb)
    INTO v_rows
  FROM public.lwb_tally_bill_rows(v_days) r
  JOIN public.orders o ON o.id = r.order_id
  LEFT JOIN public.lwb_tally_invoices t ON t.order_id = r.order_id
  WHERE r.invoice_no IS NOT NULL;

  RETURN jsonb_build_object(
    'today', (now() AT TIME ZONE 'Asia/Kolkata')::date,
    'orders', v_rows,
    'companies', (SELECT coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'color', c.color) ORDER BY c.sort_no, c.name), '[]'::jsonb)
                  FROM public.lwb_companies c WHERE c.active),
    'advance', (
      SELECT coalesce(jsonb_object_agg(z.parent, z.free), '{}'::jsonb) FROM (
        SELECT r.parent, round(sum(r.free),2) AS free FROM (
          SELECT public.lwb_party_parent(min(p.party)) AS parent,
                 sum(p.amount) - coalesce((SELECT sum(a.amount) FROM public.lwb_party_allocs a
                                           WHERE a.receipt_id = p.receipt_id AND a.cancelled_at IS NULL),0) AS free
          FROM public.lwb_tally_payments p
          WHERE p.order_id IS NULL AND p.cancelled_at IS NULL
          GROUP BY p.receipt_id) r
        GROUP BY r.parent) z
      WHERE abs(z.free) >= 0.01),
    'advance_b', (
      SELECT coalesce(jsonb_agg(jsonb_build_object('parent', z.parent, 'company_id', z.c, 'amount', z.free)), '[]'::jsonb) FROM (
        SELECT r.parent, r.c, round(sum(r.free),2) AS free FROM (
          SELECT public.lwb_party_parent(min(p.party)) AS parent, (array_agg(p.company_id))[1] AS c,
                 sum(p.amount) - coalesce((SELECT sum(a.amount) FROM public.lwb_party_allocs a
                                           WHERE a.receipt_id = p.receipt_id AND a.cancelled_at IS NULL),0) AS free
          FROM public.lwb_tally_payments p
          WHERE p.order_id IS NULL AND p.cancelled_at IS NULL
          GROUP BY p.receipt_id) r
        GROUP BY r.parent, r.c) z
      WHERE abs(z.free) >= 0.01),
    'groups', (
      SELECT coalesce(jsonb_agg(jsonb_build_object('member', m.tally_name, 'parent', btrim(m.customer_name)) ORDER BY m.customer_name, m.tally_name), '[]'::jsonb)
      FROM public.lwb_tally_party_map m
      WHERE nullif(btrim(m.customer_name),'') IS NOT NULL AND public.lwb_party_key(m.customer_name) <> m.tally_key),
    'openings', (
      SELECT coalesce(jsonb_object_agg(z.parent, z.amt), '{}'::jsonb) FROM (
        SELECT public.lwb_party_parent(b.customer_name) AS parent, sum(b.amount) AS amt
        FROM public.lwb_party_opening_balances b GROUP BY 1) z),
    'openings_b', (
      SELECT coalesce(jsonb_agg(jsonb_build_object('parent', z.parent, 'company_id', z.c, 'amount', z.amt, 'as_of', z.d)), '[]'::jsonb) FROM (
        SELECT public.lwb_party_parent(b.customer_name) AS parent, b.company_id AS c, sum(b.amount) AS amt, min(b.as_of_date) AS d
        FROM public.lwb_party_opening_balances b GROUP BY 1, 2) z),
    -- goods returned without a bill = credit on the main party (as in lwb_party_return_list)
    'returns', (
      SELECT coalesce(jsonb_agg(jsonb_build_object('party', r.party, 'parent', public.lwb_party_parent(r.party),
               'order_id', r.order_id, 'company_id', r.company_id, 'amount', r.amount, 'cancelled', false)), '[]'::jsonb)
      FROM public.lwb_party_returns r
      WHERE r.cancelled_at IS NULL AND r.order_id IS NULL
        AND r.return_date >= (now() AT TIME ZONE 'Asia/Kolkata')::date - v_days),
    'told', (
      SELECT coalesce(jsonb_object_agg(z.party, jsonb_build_object('at', z.at, 'by', z.by)), '{}'::jsonb) FROM (
        SELECT DISTINCT ON (f.party) f.party, f.created_at AS at, f.created_by_name AS by
        FROM public.lwb_payment_followups f WHERE f.order_id IS NULL AND f.created_at > now() - interval '30 days'
        ORDER BY f.party, f.created_at DESC) z)
  );
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_sales_outstanding(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_sales_outstanding(integer) TO authenticated;

-- ---------------------------------------------------------------------------
-- 3. Every payment on a PO, with mode and cheque status
--    status: WITH_DRIVER (driver reported, office not received yet), RECEIVED,
--            CHEQUE_IN_HAND, CHEQUE_DEPOSITED, CHEQUE_CLEARED, CHEQUE_BOUNCED
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.lwb_order_payments(p_ids uuid[])
RETURNS TABLE(order_id uuid, pay_date date, at timestamptz, src text, mode text, amount numeric,
              ref text, by_name text, status text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $fn$
BEGIN
  IF NOT public.lwb_outstanding_viewer() THEN
    RAISE EXCEPTION 'Admin / Accounts / Sales Head only.';
  END IF;
  IF coalesce(cardinality(p_ids), 0) > 1000 THEN
    RAISE EXCEPTION 'Max 1000 orders at a time.';
  END IF;
  RETURN QUERY
  WITH ids AS (SELECT DISTINCT x AS id FROM unnest(p_ids) AS x),
  chq AS (
    SELECT c.src AS s, c.src_id AS i, c.deposited_on FROM public.lwb_acc_cheques c
  ),
  ver AS (
    SELECT v.src AS s, v.src_id AS i, v.status AS st FROM public.lwb_acc_verify v
  ),
  -- driver money (older rows have only cash_reported + payment_mode)
  d AS (
    SELECT r.id, r.order_id AS oid, coalesce(r.payment_reviewed_at, r.reported_at) AS at,
           coalesce(dp.full_name, 'Driver') AS driver,
           CASE WHEN r.payment_status = 'VERIFIED' THEN 'RECEIVED' ELSE 'WITH_DRIVER' END AS st,
           coalesce(r.cash_amount, CASE WHEN r.online_amount IS NULL AND coalesce(r.payment_mode,'CASH') = 'CASH'
                                        THEN r.cash_reported ELSE 0 END) AS cash,
           coalesce(r.online_amount, CASE WHEN r.cash_amount IS NULL AND coalesce(r.payment_mode,'CASH') <> 'CASH'
                                          THEN r.cash_reported ELSE 0 END) AS online,
           coalesce(nullif(r.online_mode,''), nullif(regexp_replace(coalesce(r.payment_mode,''), '^CASH\+?', ''), ''), 'UPI') AS omode,
           coalesce(nullif(btrim(r.bank_ref),''), nullif(btrim(r.online_reference),''), nullif(btrim(r.payment_reference),'')) AS ref
    FROM public.lwb_delivery_reports r
    JOIN ids ON ids.id = r.order_id
    LEFT JOIN public.user_profiles dp ON dp.id = r.driver_user_id
    WHERE coalesce(r.cash_reported,0) > 0 AND coalesce(r.payment_status,'') <> 'REJECTED'
  ),
  rc AS (  -- party payment receipts that were split to these POs
    SELECT p.receipt_id, min(p.pay_date) AS pay_date, min(p.created_at) AS at,
           string_agg(DISTINCT p.mode, '+') AS mode,
           string_agg(DISTINCT nullif(btrim(p.ref_no),''), ', ') AS ref,
           (SELECT u.full_name FROM public.user_profiles u WHERE u.id = min(p.created_by::text)::uuid) AS by_name,
           min(CASE WHEN p.mode <> 'CHEQUE' THEN NULL
                    WHEN v.st = 'REJECTED' THEN 1 WHEN v.st = 'VERIFIED' THEN 4
                    WHEN c.deposited_on IS NOT NULL THEN 3 ELSE 2 END) AS chq
    FROM public.lwb_tally_payments p
    LEFT JOIN chq c ON c.s = 'PAYMENT' AND c.i = p.id
    LEFT JOIN ver v ON v.s = 'PAYMENT' AND v.i = p.id
    WHERE p.order_id IS NULL AND p.cancelled_at IS NULL
      AND p.receipt_id IN (SELECT a.receipt_id FROM public.lwb_party_allocs a JOIN ids ON ids.id = a.order_id WHERE a.cancelled_at IS NULL)
    GROUP BY p.receipt_id
  )
  SELECT d.oid, (d.at AT TIME ZONE 'Asia/Kolkata')::date, d.at, 'DRIVER'::text, 'CASH'::text, round(d.cash,2),
         NULL::text, d.driver, d.st
  FROM d WHERE d.cash > 0
  UNION ALL
  SELECT d.oid, (d.at AT TIME ZONE 'Asia/Kolkata')::date, d.at, 'DRIVER'::text,
         CASE WHEN d.omode IN ('UPI','BANK','CHEQUE') THEN d.omode ELSE 'UPI' END, round(d.online,2),
         d.ref, d.driver,
         CASE WHEN d.st = 'WITH_DRIVER' THEN d.st
              WHEN d.omode <> 'CHEQUE' THEN 'RECEIVED'
              WHEN v.st = 'REJECTED' THEN 'CHEQUE_BOUNCED' WHEN v.st = 'VERIFIED' THEN 'CHEQUE_CLEARED'
              WHEN c.deposited_on IS NOT NULL THEN 'CHEQUE_DEPOSITED' ELSE 'CHEQUE_IN_HAND' END
  FROM d
  LEFT JOIN chq c ON c.s = 'DRIVER_ONLINE' AND c.i = d.id
  LEFT JOIN ver v ON v.s = 'DRIVER_ONLINE' AND v.i = d.id
  WHERE d.online > 0
  UNION ALL
  SELECT p.order_id, p.pay_date, p.created_at, 'OFFICE'::text, p.mode, p.amount, nullif(btrim(p.ref_no),''),
         u.full_name,
         CASE WHEN p.mode <> 'CHEQUE' THEN 'RECEIVED'
              WHEN v.st = 'REJECTED' THEN 'CHEQUE_BOUNCED' WHEN v.st = 'VERIFIED' THEN 'CHEQUE_CLEARED'
              WHEN c.deposited_on IS NOT NULL THEN 'CHEQUE_DEPOSITED' ELSE 'CHEQUE_IN_HAND' END
  FROM public.lwb_tally_payments p
  JOIN ids ON ids.id = p.order_id
  LEFT JOIN public.user_profiles u ON u.id = p.created_by
  LEFT JOIN chq c ON c.s = 'PAYMENT' AND c.i = p.id
  LEFT JOIN ver v ON v.s = 'PAYMENT' AND v.i = p.id
  WHERE p.cancelled_at IS NULL
  UNION ALL
  SELECT a.order_id, rc.pay_date, a.created_at, 'PARTY'::text, coalesce(rc.mode,'CASH'), a.amount, rc.ref, rc.by_name,
         CASE rc.chq WHEN 1 THEN 'CHEQUE_BOUNCED' WHEN 2 THEN 'CHEQUE_IN_HAND' WHEN 3 THEN 'CHEQUE_DEPOSITED'
                     WHEN 4 THEN 'CHEQUE_CLEARED' ELSE 'RECEIVED' END
  FROM public.lwb_party_allocs a
  JOIN ids ON ids.id = a.order_id
  JOIN rc ON rc.receipt_id = a.receipt_id
  WHERE a.cancelled_at IS NULL
  ORDER BY 1, 3;
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_order_payments(uuid[]) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_order_payments(uuid[]) TO authenticated;

-- ---------------------------------------------------------------------------
-- 4. Tell Accounts / Cashier: "payment of this PO / party is pending, please follow up"
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.lwb_payment_followup(p_order_id uuid, p_party text DEFAULT NULL, p_note text DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_name text;
  v_note text := left(nullif(btrim(coalesce(p_note,'')),''), 300);
  v_party text;
  v_no text; v_bill text; v_due numeric;
  v_last timestamptz;
  v_title text; v_msg text;
  v_n integer := 0;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.user_profiles p WHERE p.id = auth.uid() AND p.active = true
                 AND lower(btrim(p.role)) IN ('admin','manager')) THEN
    RAISE EXCEPTION 'Only Sales Head or Admin can send this.';
  END IF;
  SELECT coalesce(nullif(btrim(u.full_name),''), 'Sales Head') INTO v_name FROM public.user_profiles u WHERE u.id = auth.uid();

  IF p_order_id IS NOT NULL THEN
    SELECT btrim(o.customer_name::text), o.order_no::text INTO v_party, v_no FROM public.orders o WHERE o.id = p_order_id;
    IF v_no IS NULL THEN RAISE EXCEPTION 'PO not found.'; END IF;
    SELECT t.invoice_no INTO v_bill FROM public.lwb_tally_invoices t WHERE t.order_id = p_order_id;
    v_due := public.lwb_order_tally_due(p_order_id);
    SELECT max(f.created_at) INTO v_last FROM public.lwb_payment_followups f WHERE f.order_id = p_order_id;
  ELSE
    v_party := left(nullif(btrim(coalesce(p_party,'')),''), 200);
    IF v_party IS NULL THEN RAISE EXCEPTION 'Choose a PO or a party.'; END IF;
    SELECT max(f.created_at) INTO v_last FROM public.lwb_payment_followups f WHERE f.order_id IS NULL AND f.party = v_party;
  END IF;
  IF v_last > now() - interval '30 minutes' THEN
    RAISE EXCEPTION 'Accounts was already told at % . Try again after 30 minutes.',
      to_char(v_last AT TIME ZONE 'Asia/Kolkata', 'HH12:MI am');
  END IF;

  v_title := 'Payment follow-up: ' || coalesce(v_party, '');
  v_msg := concat_ws(' · ', v_no, 'Bill ' || v_bill,
                     CASE WHEN v_due > 0.5 THEN 'Due ₹' || to_char(round(v_due), 'FM99,99,99,999') END,
                     v_note, 'by ' || v_name || ' (Sales Head)');

  INSERT INTO public.erp_notifications (user_id, title, message, notification_type, order_id)
  SELECT p.id, left(v_title, 200), left(v_msg, 600), 'PAYMENT_FOLLOWUP', p_order_id
  FROM public.user_profiles p
  WHERE p.active = true AND lower(btrim(p.role)) IN ('accounts','cashier','admin') AND p.id IS DISTINCT FROM auth.uid();
  GET DIAGNOSTICS v_n = ROW_COUNT;

  INSERT INTO public.lwb_payment_followups (order_id, party, note, due, sent_to, created_by, created_by_name)
  VALUES (p_order_id, coalesce(v_party, ''), v_note, v_due, v_n, auth.uid(), v_name);
  RETURN v_n;
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_payment_followup(uuid,text,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_payment_followup(uuid,text,text) TO authenticated;

COMMIT;

NOTIFY pgrst, 'reload schema';

-- Result: every row should say true.
SELECT 'outstanding data' AS item, (to_regprocedure('public.lwb_sales_outstanding(integer)') IS NOT NULL)::text AS ok
UNION ALL SELECT 'payments per PO', (to_regprocedure('public.lwb_order_payments(uuid[])') IS NOT NULL)::text
UNION ALL SELECT 'tell accounts', (to_regprocedure('public.lwb_payment_followup(uuid,text,text)') IS NOT NULL)::text
UNION ALL SELECT 'follow-up log', (to_regclass('public.lwb_payment_followups') IS NOT NULL)::text;
