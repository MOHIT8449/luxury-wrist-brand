-- Payment remarks on a party / bill (Mohit, 20 Nov 2026)
-- PO / Sales > Party Due popup: Admin and Sales Head write a short remark on a party, or on one of
-- its bills ("payment kal aayega", "payment aa gaya, Tally kar lo", any query). Accounts, Sales Head
-- and Admin read them on the popup and the Party Due cell; Accounts, Cashier, Admin and Sales Head
-- get a bell (type PAYMENT_FOLLOWUP, so it opens the same money pages).
--   * lwb_payment_remarks         table (party = main party name as shown on the popup, order_id = bill or null)
--   * lwb_payment_remark_add(party, order_id, note)  Admin / Sales Head only; returns the new row (jsonb)
--   * lwb_payment_remark_list(days)                  Admin / Accounts / Sales Head (lwb_outstanding_viewer)
-- Needs lwb_sales_head_outstanding_setup.sql (lwb_outstanding_viewer).

BEGIN;

CREATE TABLE IF NOT EXISTS public.lwb_payment_remarks (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party      text NOT NULL CHECK (length(party) BETWEEN 1 AND 200),
  order_id   uuid REFERENCES public.orders(id) ON DELETE CASCADE,
  note       text NOT NULL CHECK (length(note) BETWEEN 1 AND 300),
  created_by uuid NOT NULL,
  created_by_name text,
  created_by_role text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lwb_payment_remarks_party_idx ON public.lwb_payment_remarks(party, created_at DESC);
CREATE INDEX IF NOT EXISTS lwb_payment_remarks_order_idx ON public.lwb_payment_remarks(order_id, created_at DESC);
ALTER TABLE public.lwb_payment_remarks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.lwb_payment_remarks FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.lwb_payment_remark_add(p_party text, p_order_id uuid DEFAULT NULL, p_note text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_role text; v_name text;
  v_party text := left(nullif(btrim(coalesce(p_party,'')),''), 200);
  v_note text := left(nullif(btrim(coalesce(p_note,'')),''), 300);
  v_no text; v_bill text;
  v_row public.lwb_payment_remarks;
BEGIN
  SELECT lower(btrim(p.role)), coalesce(nullif(btrim(p.full_name),''), 'User') INTO v_role, v_name
  FROM public.user_profiles p WHERE p.id = auth.uid() AND p.active = true;
  IF v_role IS NULL OR v_role NOT IN ('admin','manager') THEN
    RAISE EXCEPTION 'Only Sales Head or Admin can write a remark.';
  END IF;
  IF v_note IS NULL THEN RAISE EXCEPTION 'Write the remark first.'; END IF;
  IF p_order_id IS NOT NULL THEN
    SELECT o.order_no::text, coalesce(v_party, btrim(o.customer_name::text)) INTO v_no, v_party FROM public.orders o WHERE o.id = p_order_id;
    IF v_no IS NULL THEN RAISE EXCEPTION 'PO not found.'; END IF;
    SELECT t.invoice_no INTO v_bill FROM public.lwb_tally_invoices t WHERE t.order_id = p_order_id;
  END IF;
  IF v_party IS NULL THEN RAISE EXCEPTION 'Choose a party.'; END IF;

  INSERT INTO public.lwb_payment_remarks (party, order_id, note, created_by, created_by_name, created_by_role)
  VALUES (v_party, p_order_id, v_note, auth.uid(), v_name, v_role)
  RETURNING * INTO v_row;

  INSERT INTO public.erp_notifications (user_id, title, message, notification_type, order_id)
  SELECT p.id, left('Payment remark: ' || v_party, 200),
         left(concat_ws(' · ', v_no, 'Bill ' || v_bill, v_note, 'by ' || v_name), 600), 'PAYMENT_FOLLOWUP', p_order_id
  FROM public.user_profiles p
  WHERE p.active = true AND lower(btrim(p.role)) IN ('accounts','cashier','admin','manager') AND p.id IS DISTINCT FROM auth.uid();

  RETURN jsonb_build_object('id', v_row.id, 'party', v_row.party, 'order_id', v_row.order_id, 'order_no', v_no,
                            'note', v_row.note, 'by_name', v_row.created_by_name, 'by_role', v_row.created_by_role,
                            'created_at', v_row.created_at);
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_payment_remark_add(text,uuid,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_payment_remark_add(text,uuid,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.lwb_payment_remark_list(p_days integer DEFAULT 120)
RETURNS TABLE (id bigint, party text, order_id uuid, order_no text, note text, by_name text, by_role text, created_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $fn$
BEGIN
  IF NOT public.lwb_outstanding_viewer() THEN
    RAISE EXCEPTION 'Admin, Accounts or Sales Head only.';
  END IF;
  RETURN QUERY
    SELECT r.id, r.party, r.order_id, o.order_no::text, r.note, r.created_by_name, r.created_by_role, r.created_at
    FROM public.lwb_payment_remarks r LEFT JOIN public.orders o ON o.id = r.order_id
    WHERE r.created_at > now() - make_interval(days => greatest(1, least(coalesce(p_days,120), 400)))
    ORDER BY r.created_at DESC
    LIMIT 3000;
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_payment_remark_list(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_payment_remark_list(integer) TO authenticated;

COMMIT;

NOTIFY pgrst, 'reload schema';

-- Result: every row should say true.
SELECT 'remarks table' AS item, (to_regclass('public.lwb_payment_remarks') IS NOT NULL)::text AS ok
UNION ALL SELECT 'write remark', (to_regprocedure('public.lwb_payment_remark_add(text,uuid,text)') IS NOT NULL)::text
UNION ALL SELECT 'read remarks', (to_regprocedure('public.lwb_payment_remark_list(integer)') IS NOT NULL)::text;
