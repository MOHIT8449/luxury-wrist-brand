-- LUXURY WRIST BRAND ERP — TALLY BILL AMOUNT MISMATCH, KEPT ON RECORD (19 Nov 2026)
--
-- Mohit (19 Nov 2026): when Accounts types a Tally bill amount that is not the PO value (e.g. PO ₹1,00,000,
-- bill ₹95,000) Billing & Outstanding shows a popup "₹5,000 short, save anyway?". When Accounts says yes,
-- the bill is saved as typed (lwb_save_tally_bills, unchanged) and the mismatch is written here, so Bills made
-- shows "⚠ ₹5,000 short" on that bill and Admin can see who OK'd it.
--
--   1. table lwb_bill_mismatches: one row each time a mismatch is OK'd (order, bill amount from the saved
--      Tally bill, expected value seen on screen, difference, basis LOADED / PO / CHANGE, PO change waiting).
--   2. lwb_bill_mismatch_note(order, expected, basis, change_id)  Accounts / Admin, after the bill is saved.
--   3. lwb_bill_mismatch_list(days)  latest row per PO, with who OK'd it.
-- Nothing else changes. Safe to run again.

BEGIN;

CREATE TABLE IF NOT EXISTS public.lwb_bill_mismatches (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  bill_amount numeric(14,2) NOT NULL,
  expected    numeric(14,2) NOT NULL,
  diff        numeric(14,2) NOT NULL,          -- bill − expected: minus = short, plus = extra
  basis       text NOT NULL DEFAULT 'LOADED' CHECK (basis IN ('LOADED','PO','CHANGE')),
  change_id   uuid,
  noted_by    uuid REFERENCES auth.users(id),
  noted_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS lwb_bill_mismatches_order ON public.lwb_bill_mismatches(order_id, noted_at DESC);
ALTER TABLE public.lwb_bill_mismatches ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.lwb_bill_mismatches FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.lwb_bill_mismatch_note(p_order_id uuid, p_expected numeric, p_basis text DEFAULT 'LOADED',
                                                         p_change_id uuid DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_bill numeric;
  v_exp numeric := round(coalesce(p_expected,0), 2);
  v_basis text := upper(btrim(coalesce(p_basis,'LOADED')));
BEGIN
  IF NOT public.lwb_tally_staff() THEN
    RAISE EXCEPTION 'Only active Accounts or Admin can enter the Tally bill';
  END IF;
  IF v_basis NOT IN ('LOADED','PO','CHANGE') THEN v_basis := 'LOADED'; END IF;
  IF v_exp <= 0 OR v_exp > 100000000 THEN RAISE EXCEPTION 'Expected value is not valid'; END IF;
  -- the amount is the saved Tally bill, not what the screen says
  SELECT t.amount INTO v_bill FROM public.lwb_tally_invoices t WHERE t.order_id = p_order_id;
  IF v_bill IS NULL THEN RAISE EXCEPTION 'Save the Tally bill first'; END IF;
  IF abs(v_bill - v_exp) <= 1 THEN
    RETURN jsonb_build_object('saved', false, 'diff', round(v_bill - v_exp, 2));
  END IF;
  INSERT INTO public.lwb_bill_mismatches (order_id, bill_amount, expected, diff, basis, change_id, noted_by)
  VALUES (p_order_id, v_bill, v_exp, round(v_bill - v_exp, 2), v_basis, p_change_id, auth.uid());
  RETURN jsonb_build_object('saved', true, 'diff', round(v_bill - v_exp, 2));
END;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_bill_mismatch_note(uuid,numeric,text,uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_bill_mismatch_note(uuid,numeric,text,uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.lwb_bill_mismatch_list(p_days integer DEFAULT 400)
RETURNS TABLE (order_id uuid, bill_amount numeric, expected numeric, diff numeric, basis text, noted_at timestamptz, noted_by text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $fn$
  SELECT DISTINCT ON (m.order_id) m.order_id, m.bill_amount, m.expected, m.diff, m.basis, m.noted_at,
         (SELECT u.full_name FROM public.user_profiles u WHERE u.id = m.noted_by)
  FROM public.lwb_bill_mismatches m
  WHERE public.lwb_tally_staff()
    AND m.noted_at >= now() - make_interval(days => least(greatest(coalesce(p_days,400),1),800))
  ORDER BY m.order_id, m.noted_at DESC;
$fn$;
REVOKE ALL ON FUNCTION public.lwb_bill_mismatch_list(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.lwb_bill_mismatch_list(integer) TO authenticated;

COMMIT;
